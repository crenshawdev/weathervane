/// Geographic region for alert provider and AQI standard selection.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Region {
    /// Continental US, Alaska, Hawaii and US territories.
    /// Uses NWS alerts and US EPA AQI.
    Us,
    /// European countries covered by MeteoAlarm. Uses European AQI.
    Europe,
    /// Canada. Uses ECCC (Environment and Climate Change Canada) alerts.
    Canada,
    /// Australia. Uses BOM (Bureau of Meteorology) alerts.
    Australia,
    /// Anywhere else. No alert provider available.
    Unknown,
}

/// Detects geographic region from coordinates for alert provider selection.
pub fn detect_region(lat: f64, lon: f64) -> Region {
    if is_us_bounds(lat, lon) {
        return Region::Us;
    }
    if is_canada_bounds(lat, lon) {
        return Region::Canada;
    }
    if is_europe_bounds(lat, lon) {
        return Region::Europe;
    }
    if is_australia_bounds(lat, lon) {
        return Region::Australia;
    }
    Region::Unknown
}

/// The US outline: the 50 states, DC and the five territories NWS answers
/// for, as rings of `lat,lon` pairs. Generated by `tools/us_outline.py` from
/// the Census TIGER/Line state file, with the land borders at about 500 m
/// and the water boundary padded out 0.3 degrees; see the script's docstring.
/// Hawaii is a box in `is_us_bounds` and is not in the file.
static US_OUTLINE: LazyLock<Vec<Vec<(f64, f64)>>> = LazyLock::new(|| {
    include_str!("us_outline.txt")
        .lines()
        .map(parse_polygon)
        .collect()
});

/// Checks if coordinates fall within US territory: the 50 states, DC, Puerto
/// Rico, the US Virgin Islands, Guam, the Northern Mariana Islands and
/// American Samoa. Follows the Canadian and Mexican borders, so a border
/// city on the other side is not US.
pub(crate) fn is_us_bounds(lat: f64, lon: f64) -> bool {
    let hawaii = (18.0..=23.0).contains(&lat) && (-161.0..=-154.0).contains(&lon);
    hawaii || US_OUTLINE.iter().any(|ring| point_in_ring(lat, lon, ring))
}

/// Checks if coordinates fall within Canada.
fn is_canada_bounds(lat: f64, lon: f64) -> bool {
    (41.0..=84.0).contains(&lat) && (-141.0..=-52.0).contains(&lon)
}

/// Checks if coordinates fall within Europe.
fn is_europe_bounds(lat: f64, lon: f64) -> bool {
    (35.0..=71.0).contains(&lat) && (-25.0..=40.0).contains(&lon)
}

/// Checks if coordinates fall within Australia.
fn is_australia_bounds(lat: f64, lon: f64) -> bool {
    (-44.0..=-10.0).contains(&lat) && (112.0..=154.0).contains(&lon)
}

/// Checks if coordinates fall within Japan (Honshu, Hokkaido, Kyushu, Shikoku, Ryukyu chain).
/// Used to gate the AMeDAS temperature override in fetch_weather.
pub(crate) fn is_japan_bounds(lat: f64, lon: f64) -> bool {
    // Honshu, Kyushu, Shikoku. West edge at 129.5E keeps South Korea
    // (Busan ~129.08E) out. Costs Tsushima (~129.3E) the override.
    let honshu = (30.5..=41.0).contains(&lat) && (129.5..=142.5).contains(&lon);

    // Hokkaido. West edge at 139.5E keeps Vladivostok (131.87E) out.
    let hokkaido = (41.0..=45.5).contains(&lat) && (139.5..=146.0).contains(&lon);

    // Ryukyu chain plus Yakushima. West edge at 122.5E keeps Taiwan
    // (north tip ~25.3N, 121.5E) out.
    let ryukyu = (24.0..=30.5).contains(&lat) && (122.5..=131.0).contains(&lon);

    honshu || hokkaido || ryukyu
}

/// Checks if a point is inside a polygon using the ray casting algorithm.
/// Polygon format: "lat1,lon1 lat2,lon2 lat3,lon3 ..."
pub(crate) fn point_in_polygon(lat: f64, lon: f64, polygon_str: &str) -> bool {
    point_in_ring(lat, lon, &parse_polygon(polygon_str))
}

/// Parses "lat1,lon1 lat2,lon2 ..." into vertices, skipping anything malformed.
fn parse_polygon(polygon_str: &str) -> Vec<(f64, f64)> {
    polygon_str
        .split_whitespace()
        .filter_map(|coord| {
            let (lat, lon) = coord.split_once(',')?;
            Some((lat.parse::<f64>().ok()?, lon.parse::<f64>().ok()?))
        })
        .collect()
}

/// Ray casting over one ring of (lat, lon) vertices. Fewer than three
/// vertices is not a polygon and contains nothing.
fn point_in_ring(lat: f64, lon: f64, vertices: &[(f64, f64)]) -> bool {
    if vertices.len() < 3 {
        return false;
    }

    let mut inside = false;
    let n = vertices.len();
    let mut j = n - 1;

    for i in 0..n {
        let (yi, xi) = vertices[i];
        let (yj, xj) = vertices[j];

        if ((yi > lat) != (yj > lat)) && (lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) {
            inside = !inside;
        }
        j = i;
    }

    inside
}

/// Encodes latitude/longitude into a geohash string.
/// Uses base32 encoding with the given precision (6 is city-level).
pub(crate) fn encode_geohash(lat: f64, lon: f64, precision: usize) -> String {
    const BASE32: &[u8] = b"0123456789bcdefghjkmnpqrstuvwxyz";

    let mut lat_range = (-90.0, 90.0);
    let mut lon_range = (-180.0, 180.0);
    let mut hash = String::with_capacity(precision);
    let mut bits = 0u8;
    let mut bit_count = 0;
    let mut is_lon = true;

    while hash.len() < precision {
        if is_lon {
            let mid = (lon_range.0 + lon_range.1) / 2.0;
            if lon >= mid {
                bits = (bits << 1) | 1;
                lon_range.0 = mid;
            } else {
                bits <<= 1;
                lon_range.1 = mid;
            }
        } else {
            let mid = (lat_range.0 + lat_range.1) / 2.0;
            if lat >= mid {
                bits = (bits << 1) | 1;
                lat_range.0 = mid;
            } else {
                bits <<= 1;
                lat_range.1 = mid;
            }
        }
        is_lon = !is_lon;
        bit_count += 1;

        if bit_count == 5 {
            hash.push(BASE32[bits as usize] as char);
            bits = 0;
            bit_count = 0;
        }
    }
    hash
}

/// Maps a point in Canada to the ECCC offices whose alert directories to read.
/// The bands overlap on purpose: every CAP entry is filtered by its own
/// polygon, so an extra office costs a few reads and a missing one costs the
/// alerts. Each office appears at most once.
pub(crate) fn get_eccc_office_codes(lat: f64, lon: f64) -> Vec<&'static str> {
    let mut offices = Vec::new();

    // British Columbia west of -114, and Yukon west of -124; both include 60N
    if (lon < -114.0 && lat <= 60.0) || (lon < -124.0 && lat >= 60.0) {
        offices.push("CWVR");
    }
    // Northwest Territories, Nunavut and the Mackenzie Delta: 60N and north
    if lat >= 60.0 {
        offices.push("CWNT");
    }
    // Alberta, Saskatchewan and Manitoba: -120 to -89
    if (-120.0..=-89.0).contains(&lon) && lat <= 60.0 {
        offices.push("CWWG");
    }
    // Ontario: -95.5 to -74, up to the Hudson Bay coast
    if (-95.5..=-74.0).contains(&lon) && lat < 57.0 {
        offices.push("CWTO");
    }
    // Quebec, Nunavik included: east of -79
    if lon > -79.0 && lat < 63.0 && lon < -57.0 {
        offices.push("CWUL");
    }
    // Atlantic provinces: east of -67 or specific lat/lon ranges
    if lon > -67.0 || (lon > -64.0 && lat < 48.0) {
        offices.push("CWHX");
    }

    // Fallback: if no office matched, return Ontario
    if offices.is_empty() {
        offices.push("CWTO");
    }

    offices
}

